// Behaviour families: how people answer a situation, with graded expressions.
// A family is chosen by the decision engine; the expression within it by personality and context.

import type { Feature } from './features';
import type { Person } from './world';
import { ON } from './world';

export type Family =
  | 'anger'
  | 'withdrawal'
  | 'seeking'
  | 'honesty'
  | 'dishonesty'
  | 'generosity'
  | 'refusal'
  | 'courage'
  | 'caution'
  | 'pride'
  | 'humility'
  | 'duty'
  | 'lapse'
  | 'discretion'
  | 'disclosure'
  | 'openness'
  | 'reluctance'
  | 'leniency'
  | 'severity'
  | 'warmth';

export interface Expression {
  id: string;
  family: Family;
  intensity: number; // 0..1, how big a deal it is
  prefers: Partial<Record<string, number>>; // facet -> weight: positive favours this expression
  needs?: Feature[]; // only possible with these features
  bars?: Feature[]; // not possible with these
  text: (a: string, t: string, thing: string, self: string, v?: number) => string; // actor, target, filler, reflexive pronoun, variant (a number; pick with V)
  evidence: Partial<Record<string, number>>; // facet -> direction*strength revealed by this expression
  like: number; // effect on the target's liking of the actor (and others who saw)
  trust: number;
  respect: number;
  stressRelief: number;
  secret?: boolean; // the act is private even if the situation wasn't
  quiet?: boolean; // never logged as an event; effects still apply
  solo?: boolean; // the target is not part of the event
  named?: boolean; // appears only where a situation names it (its `only` list), never as a general answer of its family
  needsTarget?: boolean; // needs someone to be done to or with: not possible in a situation with no counterpart
  onlyIf?: (p: Person) => boolean; // possible only for some people (walking out needs a job)
}

const E = (e: Expression) => e;
// One of several wordings, by the variant number the grammar passes (a hash of who, what and when: no random draw, so wording never
// changes behaviour). Without a number, the first wording: the one memories quote.
const V = (v: number | undefined, ...xs: string[]) => xs[(v ?? 0) % xs.length];
const poss = (s: string) => (s === 'herself' ? 'her' : 'his');

